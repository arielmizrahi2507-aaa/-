export function getFlaw(id) {
  return FLAW_LIBRARY[id] || null;
}

export function getDrillsForCategory(categoryKey) {
  return DRILLS.filter((d) => d.categories.includes(categoryKey));
}

export function getDrillsForFlaw(flawId) {
  const flaw = getFlaw(flawId);
  if (!flaw) return [];
  return getDrillsForCategory(flaw.category);
}
